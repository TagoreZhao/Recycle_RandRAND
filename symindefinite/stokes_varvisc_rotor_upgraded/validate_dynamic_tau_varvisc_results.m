function validate_dynamic_tau_varvisc_results(results_root)
%VALIDATE_DYNAMIC_TAU_VARVISC_RESULTS Validate the focused retained evidence.
    here = fileparts(mfilename('fullpath'));
    if nargin < 1 || isempty(results_root)
        results_root = fullfile(here, ...
            'benchmark_varvisc_upgraded_dynamic_tau');
    elseif ~isfolder(results_root)
        results_root = fullfile(here, results_root);
    end

    data_file = fullfile(results_root, 'all_results.csv');
    config_file = fullfile(results_root, 'run_config.mat');
    assert(isfile(data_file) && isfile(config_file), ...
        'Missing focused results or configuration in %s.', results_root);
    T = readtable(data_file);
    S = load(config_file, 'cfg_out');
    cfg = S.cfg_out;
    keys = cellstr(string(cfg.solver_keys(:)));
    expected_keys = {'ildl_nofill'; 'two_level_exact_fixed_tau'; ...
        'two_level_exact_dynamic_tau'};
    assert(isequal(keys, expected_keys), 'Unexpected focused solver registry.');
    cases = string(cfg.case_names(:));
    assert(height(T) == numel(cases) * (cfg.params.Tstep - 1), ...
        'Unexpected row count.');
    assert(cfg.params.DEFLAT_SM_EIG == 20 && ...
        cfg.params.DEFLAT_LG_EIG == 0, 'Expected exact rank-20 small-edge basis.');
    assert(cfg.params.ILDL_PREC_REFRESH == 1 && ...
        isinf(cfg.params.DEFLAT_PREC_REFRESH), ...
        'ILDL must refresh while the basis remains stale.');

    dk = 'two_level_exact_dynamic_tau';
    fk = 'two_level_exact_fixed_tau';
    tau = T.([dk '_tau']);
    cutoff = T.([dk '_cutoff_abs']);
    assert(all(isfinite(tau) & tau > 0) && ...
        all(isfinite(cutoff) & cutoff > 0), ...
        'Dynamic tau/cutoff must be finite and positive.');
    assert(max(abs(tau - cutoff.^2) ./ max(tau, eps)) < 1e-10, ...
        'Recorded tau does not equal the squared spectral cutoff.');
    assert(all(T.([dk '_deflation_rank']) == 20), ...
        'Dynamic deflation rank changed during the run.');
    assert(all(T.([dk '_basis_built_step']) == 1) && ...
        all(T.([fk '_basis_built_step']) == 1), ...
        'The stale basis was rebuilt after step 1.');
    assert(all(T.([fk '_tau']) == 0.5), 'Fixed-tau control changed tau.');

    for k = 1:numel(keys)
        key = keys{k};
        assert(all(isfinite(T.([key '_its']))) && ...
            all(T.([key '_its']) >= 0), 'Invalid iterations for %s.', key);
        assert(all(isfinite(T.([key '_time_s']))) && ...
            all(T.([key '_time_s']) >= 0), 'Invalid timings for %s.', key);
        assert(all(isfinite(T.([key '_relres']))) && ...
            max(T.([key '_relres'])) <= 1.05 * cfg.params.SOLVER_TOL, ...
            'Split-residual acceptance failed for %s.', key);
        residual_limit = 100 * cfg.params.SOLVER_TOL;
        error_limit = 1000 * cfg.params.SOLVER_TOL;
        assert(all(isfinite(T.([key '_true_relres']))) && ...
            max(T.([key '_true_relres'])) < residual_limit, ...
            'True-residual acceptance failed for %s.', key);
        assert(all(isfinite(T.([key '_err']))) && ...
            max(T.([key '_err'])) < error_limit, ...
            'Solution-error acceptance failed for %s.', key);
    end
    assert(max(T.backslash_relres) < 1e-8 && ...
        max(T.constraint_res) < 1e-8, ...
        'Direct solve or physical constraint acceptance failed.');

    expected_nC = containers.Map( ...
        {'current_channel_ar4', 'mixer_circle_four_blade'}, {6, 18});
    for k = 1:numel(cases)
        cname = char(cases(k));
        rows = string(T.case_name) == cases(k);
        assert(all(T.nC(rows) == expected_nC(cname)), ...
            'Unexpected constraint count for %s.', cname);
        assert(isfile(fullfile(results_root, 'iteration_vs_timestep', ...
            [cname '_linear.png'])), 'Missing linear plot for %s.', cname);
        assert(isfile(fullfile(results_root, 'iteration_vs_timestep', ...
            [cname '_log.png'])), 'Missing log plot for %s.', cname);
    end
    assert(isfile(fullfile(results_root, 'dynamic_tau_summary.csv')), ...
        'Missing dynamic tau summary.');
    if ~contains(results_root, 'smoke')
        assert(cfg.params.h0 == 0.05 && cfg.params.dt == 0.02 && ...
            cfg.params.Tstep == 61 && cfg.physical_Tmax == 1.2, ...
            'Full-run physical mesh/time parameters changed.');
    end
    fprintf(['validate_dynamic_tau_varvisc_results: PASS ' ...
        '(%d rows, %d cases, rank 20)\n'], height(T), numel(cases));
end
